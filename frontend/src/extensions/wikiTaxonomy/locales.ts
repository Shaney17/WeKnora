let registered = false

/** Merge the extension's messages into the app's i18n instance (idempotent). */
export function registerWikiTaxonomyMessages() {
  if (registered) return
  registered = true
  for (const [locale, messages] of Object.entries(wikiTaxonomyMessages)) {
    i18n.global.mergeLocaleMessage(locale, { extensions: { wikiTaxonomy: messages } })
  }
}
